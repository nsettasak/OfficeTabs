<#
.SYNOPSIS
    Sets the project version in the one place it is written.
.DESCRIPTION
    Everything else derives from Cargo.toml: the Win32 version resource is
    generated by build.rs, and the MSI ProductVersion and ProductCode come
    from scripts/build-msi.ps1. This script edits Cargo.toml and refreshes
    Cargo.lock so the next `cargo build --locked` still matches.
.EXAMPLE
    ./scripts/bump-version.ps1 0.34.0
#>
param([Parameter(Mandatory = $true)][string]$Version)
$ErrorActionPreference = 'Stop'
if ($Version -notmatch '^\d+\.\d+\.\d+$') { throw "Version must look like 0.34.0, got '$Version'" }
$root = Split-Path $PSScriptRoot -Parent
$cargo = Join-Path $root 'Cargo.toml'
$text = [IO.File]::ReadAllText($cargo)
if ($text -notmatch '(?m)^version\s*=\s*"') { throw 'No version line in Cargo.toml' }
$updated = [regex]::Replace($text, '(?m)^version\s*=\s*"[^"]+"', 'version = "' + $Version + '"', 1)
[IO.File]::WriteAllText($cargo, $updated, (New-Object Text.UTF8Encoding $false))
Push-Location $root
try {
    # Refresh only this package's entry in Cargo.lock; dependencies stay pinned.
    cargo update -p officetabs-native | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'cargo update failed; check Cargo.toml' }
} finally { Pop-Location }
Write-Host "Version set to $Version."
Write-Host "Derived automatically: Win32 resource (build.rs), MSI ProductVersion/ProductCode,"
Write-Host "installer name. Next: ./scripts/build.ps1, which runs the tests and the audits."
